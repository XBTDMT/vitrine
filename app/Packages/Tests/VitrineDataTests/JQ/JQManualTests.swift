import XCTest
@testable import VitrineData

/// The jq 1.7 manual's behaviour, case by case: (program, input, outputs as `jq -c` prints them). Inputs are the
/// manual's own tiny generic examples or invented ones; expectations follow the manual's semantics.
final class JQManualTests: XCTestCase {
    func testBasicFilters() {
        JQT.check([
            .init(".", #""Hello, world!""#, [#""Hello, world!""#]),
            .init(".foo", #"{"foo": 42, "bar": "less interesting data"}"#, ["42"]),
            .init(".foo", #"{"notfoo": true, "alsonotfoo": false}"#, ["null"]),
            .init(#".["foo"]"#, #"{"foo": 42}"#, ["42"]),
            .init(".foo?", #"{"foo": 42, "bar": "less interesting data"}"#, ["42"]),
            .init(".foo?", #"{"notfoo": true, "alsonotfoo": false}"#, ["null"]),
            .init(#".["foo"]?"#, #"{"foo": 42}"#, ["42"]),
            .init("[.foo?]", "[1,2]", ["[]"]),
            .init(".[0]", #"[{"name":"JSON", "good":true}, {"name":"XML", "good":false}]"#, [#"{"name":"JSON","good":true}"#]),
            .init(".[2]", #"[{"name":"JSON", "good":true}, {"name":"XML", "good":false}]"#, ["null"]),
            .init(".[-2]", "[1,2,3]", ["2"]),
            .init(".[2:4]", #"["a","b","c","d","e"]"#, [#"["c","d"]"#]),
            .init(".[2:4]", #""abcdefghi""#, [#""cd""#]),
            .init(".[:3]", #"["a","b","c","d","e"]"#, [#"["a","b","c"]"#]),
            .init(".[-2:]", #"["a","b","c","d","e"]"#, [#"["d","e"]"#]),
            .init(".[]", #"[{"name":"JSON", "good":true}, {"name":"XML", "good":false}]"#,
                  [#"{"name":"JSON","good":true}"#, #"{"name":"XML","good":false}"#]),
            .init(".[]", "[]", []),
            .init(".foo[]", #"{"foo":[1,2,3]}"#, ["1", "2", "3"]),
            .init(".[]", #"{"a": 1, "b": 1}"#, ["1", "1"]),
            .init(".[]?", "5", []),
            .init(".foo, .bar", #"{"foo": 42, "bar": "something else", "baz": true}"#, ["42", #""something else""#]),
            .init(".user, .projects[]", #"{"user":"stedolan", "projects": ["jq", "wikiflow"]}"#,
                  [#""stedolan""#, #""jq""#, #""wikiflow""#]),
            .init(".[4,2]", #"["a","b","c","d","e"]"#, [#""e""#, #""c""#]),
            .init(".[] | .name", #"[{"name":"JSON", "good":true}, {"name":"XML", "good":false}]"#, [#""JSON""#, #""XML""#]),
