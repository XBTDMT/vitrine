#!/usr/bin/env python3
"""Generate VitrineUI's token tables from the approved design system.

Reads design/mockups/unified/tokens.json (the unified design system, G-8) and writes
app/Packages/Sources/VitrineUI/Tokens.generated.swift: every system colour (CSS `--v-<name>`) in light and dark, and
the Markdown theme Collection with its type and colours. The build never copies a colour by hand; change tokens.json
and re-run this script.

Usage (from the repository root): python3 -I app/tools/gen_tokens.py
roadmap: S-4, S-10
"""
import json
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
src = root / "design/mockups/unified/tokens.json"
out = root / "app/Packages/Sources/VitrineUI/Tokens.generated.swift"

THEME_KEYS = ["bg", "fg", "fg2", "acc", "rule", "code", "sk", "ss", "sn", "sc", "sf", "hl"]
COLOR = re.compile(r"^(#[0-9A-Fa-f]{6}|#[0-9A-Fa-f]{8}|rgba?\([0-9.,\s]+\)|linear-gradient\([^;{}]+\))$")


def swift(s):
    """A Swift string literal; refuses anything that would need escaping beyond quotes."""
    if "\\" in s or "\n" in s:
        sys.exit(f"gen_tokens: value needs escaping, refusing: {s!r}")
    return '"' + s.replace('"', '\\"') + '"'


def css_value(v, where):
    if not COLOR.match(v):
        sys.exit(f"gen_tokens: {where} is not a colour this generator understands: {v!r}")
    return v


# A box-shadow list: lengths, rgba() and hex colours, inset, and the system's own --v- tokens; nothing else.
SHADOW = re.compile(r"(inset |-?[0-9.]+(px)? |-?[0-9.]+(px)?|rgba?\([0-9., ]+\)|#[0-9A-Fa-f]{3,8}|var\(--v-[a-z0-9-]+\)|,| )+")


def shadow_value(v, where):
    if not SHADOW.fullmatch(v):
        sys.exit(f"gen_tokens: {where} is not a shadow this generator understands: {v!r}")
    return v


def px(v, where):
    m = re.fullmatch(r"([0-9.]+)px", v)
    if not m:
        sys.exit(f"gen_tokens: {where} is not a px length: {v!r}")
    return m.group(1)


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def num(v):
    return f"{v:g}"


def metrics(d):
    """The non-colour tokens as CSS values, in the order system.html writes them."""
    out = []
    for name, v in d["material"].items():
        out.append((name, v["backdropFilter"]))
    for name, v in d["radius"].items():
        out.append((name, f"{num(v['pt'])}px"))
    for n in d["spacing"]:
        out.append((f"sp-{n}", f"{n}px"))
    for name, v in d["size"].items():
        out.append((name, f"{num(v['pt'])}px"))
    for name, v in d["type"].items():
        out += [(name, f"{num(v['size'])}px"), (name + "-w", str(v["weight"])), (name + "-lh", num(v["lineHeight"]))]
    for name, v in d["font"].items():
        out.append((name, v))
    for name, v in d["motion"]["duration"].items():
        out.append((name, f"{num(v['ms'])}ms"))
    for name, v in d["motion"]["curve"].items():
        out.append((name, v["value"]))
    for name, value in out:
        if not re.fullmatch(r"[a-z0-9-]+", name) or "\\" in value or ";" in value:
            sys.exit(f"gen_tokens: metric {name!r} = {value!r} is not a CSS custom property this generator writes")
    return out


def main():
    d = json.loads(src.read_text())
    if d.get("cssPrefix") != "--v-" or d.get("modes") != ["light", "dark"]:
        sys.exit("gen_tokens: tokens.json changed shape (cssPrefix or modes); update this generator")
    lines = [
        f"// Generated by app/tools/gen_tokens.py from design/mockups/unified/tokens.json (system v{d['version']}, {d['date']}).",
        "// Do not edit: change tokens.json and re-run the script. roadmap: S-4, S-10",
        "",
        "public enum GeneratedTokens {",
        f"    public static let version = {int(d['version'])}",
        "",
        "    /// Every system colour, in tokens.json order. CSS name `--v-<name>`.",
        "    public static let colors: [ColorToken] = [",
    ]
    for name, v in d["color"].items():
        if not re.fullmatch(r"[a-z0-9-]+", name):
            sys.exit(f"gen_tokens: colour name {name!r} is not a CSS identifier")
        lines.append(f"        ColorToken(name: {swift(name)}, light: {swift(css_value(v['light'], name + '.light'))}, "
                     f"dark: {swift(css_value(v['dark'], name + '.dark'))}),")
    lines += ["    ]", "", "    /// Every shadow, light and dark (CSS box-shadow lists for the pages; S-15 redman). CSS name `--v-<name>`.",
              "    public static let shadows: [ColorToken] = ["]
    for name, v in d["shadow"].items():
        if not re.fullmatch(r"[a-z0-9-]+", name):
            sys.exit(f"gen_tokens: shadow name {name!r} is not a CSS identifier")
        lines.append(f"        ColorToken(name: {swift(name)}, light: {swift(shadow_value(v['light'], name + '.light'))}, "
                     f"dark: {swift(shadow_value(v['dark'], name + '.dark'))}),")
    lines += ["    ]", "", "    /// Every size, radius, type, font, material and motion value, mode-independent. CSS name `--v-<name>`.",
              "    public static let metrics: [(name: String, value: String)] = ["]
    for name, value in metrics(d):
        lines.append(f"        ({swift(name)}, {swift(value)}),")
    lines += ["    ]", "", "    /// The Markdown theme Collection, in the order Settings lists it. The first is the default.",
              "    public static let markdownThemes: [MarkdownThemeSpec] = ["]
    seen = set()
    for name, t in d["markdownThemes"]["themes"].items():
        tid = slug(name)
        if tid in seen:
            sys.exit(f"gen_tokens: two themes slug to {tid!r}")
        seen.add(tid)
        ty = t["type"]
        cols = {}
        for mode in ("light", "dark"):
            missing = set(THEME_KEYS) ^ set(t[mode])
            if missing:
                sys.exit(f"gen_tokens: theme {name} {mode} keys differ: {sorted(missing)}")
            if not t[mode]["bg"].startswith("#"):
                sys.exit(f"gen_tokens: theme {name} {mode} bg must be a hex colour (it backs the web view)")
            cols[mode] = "ThemeColors(" + ", ".join(
                f"{k}: {swift(css_value(t[mode][k], f'{name}.{mode}.{k}'))}" for k in THEME_KEYS) + ")"
        lines.append(
            f"        MarkdownThemeSpec(id: {swift(tid)}, name: {swift(name)}, font: {swift(ty['font'])}, "
            f"headingFont: {swift(ty['hfont'])}, mono: {swift(ty['mono'])}, size: {px(ty['fs'], name + '.fs')}, "
            f"lineHeight: {float(ty['lh'])}, measure: {int(float(px(ty['measure'], name + '.measure')))}, "
            f"headingWeight: {int(ty['hw'])},\n"
            f"                          light: {cols['light']},\n"
            f"                          dark: {cols['dark']}),")
    lines += ["    ]", "}", ""]
    out.write_text("\n".join(lines))
    print(f"wrote {out.relative_to(root)}: {len(d['color'])} colours, {len(seen)} Markdown themes")


if __name__ == "__main__":
    main()
