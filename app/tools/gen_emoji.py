#!/usr/bin/env python3
"""Generates Packages/Sources/VitrineText/EmojiTable.generated.swift from GitHub's gemoji db (MIT).
Usage: python3 -I tools/gen_emoji.py /path/to/emoji.json   (download: https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json)
roadmap: S-4"""
import json, sys, pathlib
src = pathlib.Path(sys.argv[1]); out = pathlib.Path(__file__).resolve().parent.parent / "Packages/Sources/VitrineText/EmojiTable.generated.swift"
rows = []
for e in json.load(src.open()):
    if "emoji" not in e: continue
    for a in e.get("aliases", []):
        if a.replace("_", "").replace("+", "").replace("-", "").isalnum():
            rows.append((a, e["emoji"]))
rows.sort()
lines = ["// Generated by tools/gen_emoji.py from github/gemoji db/emoji.json (MIT). Do not edit.",
         "// roadmap: S-4", "", "enum EmojiTable {", "    static let shortcodes: [String: String] = ["]
for a, em in rows:
    esc = "".join("\\u{%X}" % ord(c) for c in em)
    lines.append('        "%s": "%s",' % (a, esc))
lines += ["    ]", "}", ""]
out.write_text("\n".join(lines)); print(f"{len(rows)} shortcodes -> {out}")
